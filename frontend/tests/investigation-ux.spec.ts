test('import source tabs preserve independent drafts, automatic scans and long UNC paths', async ({ page }) => {
  const longPath = '\\\\DEMO-SERVER\\exports\\' + 'synthetic-folder\\'.repeat(18) + 'users.csv'
  let detections = 0
  await page.route('**/api/user-import/headers', async route => { detections++; await route.fulfill({ json: { detected_columns: ['USERNAME', 'ROLE_NAME'], issues: [] } }) })
  await page.route('**/api/user-import/preview', async route => route.fulfill({ json: { parsed_rows: 1, unique_users: 1, assignments: 1, duplicate_rows: 0, warnings: [] } }))
  await page.goto('/#session=browser-test-session')
  await page.getByRole('button', { name: 'Open settings', exact: true }).click()
  await page.getByRole('tab', { name: 'Data Sources', exact: true }).click()
  const rolePath = await page.getByLabel('CSV file location', { exact: true }).inputValue()
  await page.getByRole('tab', { name: 'User Access', exact: true }).click()
  await page.getByText('Advanced import format and column mapping',{exact:true}).click()
  await page.getByLabel('User CSV file location', { exact: true }).fill(longPath)
  for (const label of ['Parsed rows','SAP users']) await expect(page.locator('.preview-metrics > div').filter({has:page.getByText(label,{exact:true})}).locator('dd')).toHaveText('1')
  expect(detections).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Detect user columns', exact: true }).click()
  await expect.poll(() => detections).toBeGreaterThan(1)
  await page.getByRole('tab', { name: 'Role Catalogue', exact: true }).click()
  await expect(page.getByLabel('CSV file location', { exact: true })).toHaveValue(rolePath)
  await page.getByRole('tab', { name: 'User Access', exact: true }).click()
  await expect(page.getByLabel('User CSV file location', { exact: true })).toHaveValue(longPath)
  await expect(page.getByLabel('CSV file location', { exact: true })).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})

