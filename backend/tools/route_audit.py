"""Route-level parity audit (Phase 3.1): every API route string the React UI references (frontend/src) against the v1 routes the .NET server
implements (V1Compatibility.Migrated). Everything not implemented is answered by the explicit 501 catch-all. Regenerate after every migration step:

  python -I route_audit.py REPO_ROOT OUT_MARKDOWN"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
pattern = re.compile(r"['`\"](/api/[A-Za-z0-9_/{}$.:-]*)")
routes = {}
for file in sorted((root / 'frontend' / 'src').rglob('*.ts*')):
    for match in pattern.finditer(file.read_text(encoding='utf-8')):
        raw = match.group(1)
        route = re.sub(r'\$\{[^}]*\}?', '{x}', raw)
        route = re.sub(r'\$.*$', '{x}', route).rstrip('/')
        route = re.sub(r'\{x\}[^/]*', '{x}', route)
        routes.setdefault(route, set()).add(str(file.relative_to(root)))

source = (root / 'backend/src/AuthLens.Api/V1Compatibility.cs').read_text(encoding='utf-8')
block = source[source.index('public static readonly string[] Migrated'):]
block = block[:block.index('];')]
implemented = {}
for method, path in re.findall(r'"(GET|POST|PUT|DELETE) (/api/[^"]*)"', block):
    implemented.setdefault(re.sub(r'\{[^}]*\}', '{x}', path), set()).add(method)


# UI strings built by concatenation or a template whose concrete values are known from the code (the value list is the whole set the UI can
# produce). Such a route counts as implemented only when every concrete route is; the table names the values, so nothing is hidden behind {x}.
TEMPLATES = {
    '/api/access/exports/{x}': ['/api/access/exports/users', '/api/access/exports/release-roles', '/api/access/exports/releases'],   # useAssignmentCSVExport view
    '/api/auth': ['/api/auth/reset', '/api/auth/recover'],   # Authentication.tsx: '/api/auth/' + ('reset' | 'recover')
}


def status(route):
    if route in TEMPLATES:
        missing = [r for r in TEMPLATES[route] if r not in implemented]
        methods = sorted({m for r in TEMPLATES[route] if r in implemented for m in implemented[r]})
        values = ', '.join(r.rsplit('/', 1)[1] for r in TEMPLATES[route])
        return ('implemented', f'{", ".join(methods)} (values: {values})') if not missing else ('not migrated (501)', 'missing: ' + ', '.join(missing))
    if route in implemented:
        return 'implemented', ', '.join(sorted(implemented[route]))
    # A UI string that is a prefix of an implemented parameterised route (for example `/api/roles/` + name).
    for path, methods in implemented.items():
        if path.startswith(route + '/{x}') or route.endswith('{x}') and path.startswith(route[:-3]) and path.endswith('{x}'):
            return 'implemented', ', '.join(sorted(methods))
    return 'not migrated (501)', ''


rows = sorted((route, *status(route), sorted(files)[0]) for route, files in routes.items())
done = sum(1 for r in rows if r[1] == 'implemented')
area = {}
for route, state, _, _ in rows:
    key = route.split('/')[2]
    total, ok = area.get(key, (0, 0))
    area[key] = (total + 1, ok + (state == 'implemented'))
lines = ['# Route audit (generated)', '',
         f'Generated by `backend/tools/route_audit.py` from `frontend/src` and `V1Compatibility.Migrated`. **{done} of {len(rows)}** distinct API '
         'route strings referenced by the React UI are served by the .NET server; every other route answers `501` with `code: not_migrated` '
         '(contract-tested), so no route returns invented data. Method-level behaviour of implemented routes is covered by the contract tests; a route '
         'listed as implemented may still refuse individual filters with 501 (see FEATURE_PARITY.md).', '',
         '## By area', '', '| Area | Implemented | Referenced |', '| --- | ---: | ---: |']
lines += [f'| `{key}` | {ok} | {total} |' for key, (total, ok) in sorted(area.items())]
lines += ['', '## Routes', '', '| Route (UI reference) | .NET status | Methods | First UI reference |', '| --- | --- | --- | --- |']
lines += [f'| `{route}` | {state} | {methods} | `{file}` |' for route, state, methods, file in rows]
Path(sys.argv[2]).write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'{done} of {len(rows)} routes implemented; wrote {sys.argv[2]}')
