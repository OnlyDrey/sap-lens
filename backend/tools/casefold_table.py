"""Writes src/AuthLens.Domain/Text/CasefoldTable.g.cs: every code point whose Python str.casefold(), str.upper() or str.lower() differs from the code
point itself (full Unicode case mappings, including multi-character ones such as German sharp s to "SS").

Run with the Python version SAP Lens v1 uses (3.12): python3.12 tools/casefold_table.py src/AuthLens.Domain/Text/CasefoldTable.g.cs"""
import sys
import unicodedata

def table(mapping):
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        f = mapping(c)
        if f != c:
            rows.append(f"{cp:X}:{' '.join(f'{ord(x):X}' for x in f)}")
    body = ';'.join(rows)
    chunks = [body[i:i + 160] for i in range(0, len(body), 160)]
    return len(rows), '\n'.join(f'        "{chunk}"' + (' +' if i < len(chunks) - 1 else ';') for i, chunk in enumerate(chunks))


tables = {name: table(fn) for name, fn in (('Casefold', str.casefold), ('Upper', str.upper), ('Lower', str.lower))}
with open(sys.argv[1], 'w', encoding='utf-8', newline='\n') as out:
    out.write('// <auto-generated>tools/casefold_table.py, Python %s, Unicode %s</auto-generated>\n' % (sys.version.split()[0], unicodedata.unidata_version))
    out.write('namespace AuthLens.Domain.Text;\n\ninternal static class CasefoldTable\n{\n')
    out.write('    public const string UnicodeVersion = "%s";\n' % unicodedata.unidata_version)
    for name, (_, text) in tables.items():
        out.write(f'    /// <summary>str.{name.lower()}(): "codepoint:mapped codepoints" pairs separated by ";" (hex).</summary>\n    public const string {name} =\n')
        out.write(text + '\n')
    out.write('}\n')
print({name: count for name, (count, _) in tables.items()})
